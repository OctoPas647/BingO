(function buildBelBank() {
  const PROMPTS = {
    spell: ['Кое е написано правилно?', 'Коя от думите е написана **неправилно**?'],
    art: ['Изберете правилно написаното изречение.', 'В кое изречение има **грешка** в членуването?'],
    comma: ['В кое изречение пунктуацията е **правилна**?', 'В кое изречение има **грешка** в пунктуацията?']
  };
  const rows = [];
  for (const [skill, text] of Object.entries(BEL_ROWS)) {
    let k = 0;
    text.split('\n').forEach(line => {
      line = line.trim(); if (!line) return;
      const f = line.split('|');
      if (f.length < 5) { console.warn('bad BEL row', line); return; }
      rows.push({ skill, k: k++, level: +f[0] || 2, right: f[1], wrong: f.slice(2, -2), code: skill + '.' + f[f.length - 2], explain: f[f.length - 1] });
    });
  }
  const mk = (id, r, prompt, opts, ans, misc, explain) => {
    const order = shuffledIdx(opts.length, id);
    return { id, skill: r.skill, level: r.level, type: 'choice', prompt, options: order.map(i => opts[i]), answer: order.indexOf(ans), misc: order.map(i => misc[i]), explain };
  };
  for (const r of rows) {
    const key = r.skill + String(r.k).padStart(3, '0');
    BEL_BANK.push(mk('b2:' + key + ':r', r, PROMPTS[r.skill][0], [r.right, ...r.wrong], 0, [null, ...r.wrong.map(() => r.code)], r.explain));
    const same = rows.filter(x => x !== r && x.skill === r.skill && x.code === r.code), any = rows.filter(x => x !== r && x.skill === r.skill);
    const pool = (same.length >= 2 ? same : any).slice(), R = seedRng('b2:' + key + ':e'), others = [];
    while (others.length < 2 && pool.length) others.push(pool.splice(Math.floor(R.f() * pool.length), 1)[0]);
    if (others.length < 2) continue;
    const lvl = Math.min(3, r.level + (r.level < 3 && R.chance(0.3) ? 1 : 0));
    const t = mk('b2:' + key + ':e', { ...r, level: lvl }, PROMPTS[r.skill][1], [r.wrong[0], others[0].right, others[1].right], 0, [null, null, null], 'Грешката е във варианта „' + r.wrong[0] + '“. Правилно е: ' + r.right + '. ' + r.explain);
    BEL_BANK.push(t);
  }
})();
