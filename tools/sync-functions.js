/* Copies BingO's answer checking (Shelly's engine/js/00-util.js + 03-scoring.js, BingO's src/js/48-scoring.js and the class rules in src/js/70-edu-core.js)
   into functions/shared/edu.js, so Cloud Functions grade a class test with exactly the same code the app uses.
   Run it after a change to those files:  node tools/sync-functions.js   (tools/check.js fails while the copy is stale) */
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const SOURCES = ['engine/js/00-util.js', 'engine/js/03-scoring.js', 'src/js/48-scoring.js', 'src/js/70-edu-core.js'];
const OUT = path.join(ROOT, 'functions/shared/edu.js');

function build() {
  const body = SOURCES.map(f => `/* ==== ${f} ==== */\n` + fs.readFileSync(path.join(ROOT, f), 'utf8')).join('\n');
  return `/* GENERATED by tools/sync-functions.js from ${SOURCES.join(', ')}. Do not edit by hand. */
'use strict';
${body}
Object.assign(module.exports, { scoreTask: (t, r, l) => scoreTask(t, r, l), applyScale, textMatches: (...a) => textMatches(...a), parseNumber, roundTo, clamp, shuffled, rng, arr, sum, isObj });
`;
}

if (require.main === module) {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, build());
  console.log('  functions/shared/edu.js updated');
}
module.exports = { build, OUT };
